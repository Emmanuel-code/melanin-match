#!/usr/bin/env python3
"""Embed the app's photos into lib/images.ts as data URIs.

Why: the repo is synced through a text-only snapshot push, which cannot
carry binary JPGs. The originals stay in assets/ as the source of truth;
this script resizes them (max width 900, JPEG q72) and regenerates
lib/images.ts. Re-run after replacing any photo:

    python3 scripts/embed-images.py
"""
import base64
import io
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
OUT = ROOT / "lib" / "images.ts"

PHOTOS = [
    ("HERO_IMG", "hero.jpg"),
    ("ONBOARDING_PROBLEM_IMG", "onboarding-problem.jpg"),
    ("ONBOARDING_PROOF_IMG", "onboarding-proof.jpg"),
    # Anastasia — founder of Peach Cosmetics. The founder portrait dresses
    # the boutique; the sample is a face-tight crop of the same photo so
    # the demo sample clears the skin-analysis face-size rule (>60% width).
    ("FOUNDER_IMG", "anastasia-founder.jpg"),
    ("SAMPLE_IMG", "anastasia-sample.jpg"),
]


def data_uri(path: pathlib.Path) -> str:
    im = Image.open(path).convert("RGB")
    if im.width > 900:
        im = im.resize((900, round(im.height * 900 / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=72, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


lines = [
    "// GENERATED by scripts/embed-images.py — do not edit by hand.",
    "// Photos embedded as data URIs so the text-only repo sync can carry them;",
    "// originals live in assets/. Re-run the script after replacing a photo.",
    "",
]
for name, fname in PHOTOS:
    uri = data_uri(ASSETS / fname)
    lines.append(f"export const {name} = '{uri}';")
    print(f"{name}: {len(uri) // 1024} KB data URI")

OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT)
